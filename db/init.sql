-- Oracle 컨테이너(gvenzl/oracle-free)가 처음 만들어질 때 한 번 실행됨
-- 기존 DB에 직접 만들 때는 FREEPDB1에 system으로 접속해서 CREATE TABLE부터 실행
ALTER SESSION SET CONTAINER = FREEPDB1;

CREATE TABLE SYSTEM.STOCK_SENTIMENT (
    ID               NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    TICKER           VARCHAR2(20) NOT NULL,       -- 종목 코드 (예: AAPL, 005930.KS)
    TARGET_DATE      DATE NOT NULL,               -- 분석 대상 거래일
    COMPANY_NAME     VARCHAR2(100),
    OPEN_PRICE       NUMBER,
    CLOSE_PRICE      NUMBER,
    TRADING_VOLUME   NUMBER,
    MARKET_SENTIMENT VARCHAR2(20),                -- 긍정 / 중립 / 부정
    ANALYSIS_REASON  VARCHAR2(2000),
    CREATED_AT       TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT UQ_STOCK_DATE UNIQUE (TICKER, TARGET_DATE)
);
